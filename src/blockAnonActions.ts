/**
 * Determines whether AWS rejects unsigned requests for an IAM action, regardless of resource policy.
 *
 * @param servicePrefix the IAM service prefix for the action.
 * @param actionName the IAM action name.
 * @returns true when the action blocks anonymous requests.
 */
export function actionBlocksAnonymousAccess(servicePrefix: string, actionName: string): boolean {
  return blockAnonActions.has(`${servicePrefix}:${actionName}`.toLowerCase())
}

/**
 * Adds sparse anonymous-access metadata to an IAM action definition.
 *
 * @param servicePrefix the IAM service prefix for the action.
 * @param action the generated IAM action definition.
 * @returns the action definition with blockAnon true only when AWS blocks anonymous access.
 */
export function addBlockAnonMetadata<T extends { name: string }>(
  servicePrefix: string,
  action: T
): T & { blockAnon?: true } {
  if (!actionBlocksAnonymousAccess(servicePrefix, action.name)) {
    return action
  }

  return { ...action, blockAnon: true }
}
